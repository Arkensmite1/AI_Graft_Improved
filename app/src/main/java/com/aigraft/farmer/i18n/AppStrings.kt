enum class PlanIcon { COVER, SHADE, CAMERA, WIND, SUN, WATER, EYE, CLIP, CHECK }

@Immutable
data class PlanTask(
    val day: Int,
    val icon: PlanIcon,
    val en: String,
    val hi: String,
    val photo: Boolean = false,
    val milestone: Boolean = false,
) {
    fun text(lang: AppLang): String = if (lang == AppLang.EN) en else hi
}

