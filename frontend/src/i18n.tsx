const dict: Record<Lang, Strings> = { en, hi };
const KEY = "app_lang";

type Ctx = { lang: Lang; t: Strings; setLang: (l: Lang) => void };
const LangContext = createContext<Ctx>({ lang: "hi", t: hi, setLang: () => {} });

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("hi");

  useEffect(() => {
    storage.getItem(KEY, "hi").then((v) => {
      if (v === "en" || v === "hi") setLangState(v);
    });
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    storage.setItem(KEY, l);
  }, []);

  return <LangContext.Provider value={{ lang, t: dict[lang], setLang }}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);
